export function ikona(nazwa, klasa = '') {
  const s = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  s.setAttribute('viewBox', '0 0 24 24');
  s.setAttribute('aria-hidden', 'true');
  s.setAttribute('class', `ik ${klasa}`.trim());
  s.innerHTML = SCIEZKI[nazwa] || '';
  return s;
}

export function wstawIkony(korzen = document) {
  for (const e of korzen.querySelectorAll('[data-ikona]')) e.replaceWith(ikona(e.dataset.ikona, e.className));
}
